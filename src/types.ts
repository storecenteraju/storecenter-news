export type CategoryType = 
  | 'Economia'
  | 'Política'
  | 'Negócios'
  | 'Tecnologia'
  | 'Geopolítica'
  | 'Nacional'
  | 'Esporte'
  | 'Saúde'
  | 'Entretenimento';

export interface Post {
  id: string;
  title: string;
  subtitle: string;
  slug: string;
  content: string;
  category: CategoryType;
  tags: string[];
  author: string;
  date: string; // ISO string or YYYY-MM-DD HH:MM
  status: 'published' | 'draft' | 'scheduled';
  publishAt?: string; // for scheduled
  image: string; // URL or base64 or placeholder
  seoTitle: string;
  seoDescription: string;
  keyword: string;
  imagePrompt?: string; // prompt generated by IA
  views: number;
}

export interface RSSFeed {
  id: string;
  name: string;
  url: string;
  category: CategoryType;
  status: 'active' | 'inactive';
  lastScraped?: string;
}

export interface AdUnit {
  id: string;
  name: string;
  slot: 'top' | 'middle' | 'bottom' | 'sidebar' | 'footer' | 'floating';
  code: string;
  enabled: boolean;
}

export interface SiteSettings {
  siteName: string;
  siteDescription: string;
  footerText: string;
  analyticsId: string;
  contactEmail: string;
}

export interface LinkComparisonResult {
  title: string;
  subtitle: string;
  content: string;
  seoTitle: string;
  seoDescription: string;
  tags: string[];
  category: CategoryType;
  conflicts: string; // Descrição de eventuais contradições, ou "Sem conflitos"
  imagePrompt: string;
  sourcesAnalyzed: string[];
}
