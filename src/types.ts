export function normalizePost(post: any): Post {
  if (!post) return post;
  const p = { ...post };

  // Marcadores usados internamente na consolidação de fontes nunca devem ser
  // exibidos ao leitor (inclusive na cópia estática do portal).
  if (typeof p.title === 'string') {
    p.title = p.title
      .replace(/^\s*\[?Fonte\s*["'“”]?\s*1\]?\s*[:\-—]?\s*/i, '')
      .split(/\s*\[?Fonte\s*2\]?\b/i)[0]
      .trim();
  }

  // Normalize status - handle "NO AR", boolean "published"
  const rawStatus = String(p.status || '').trim().toLowerCase();
  
  if (
    rawStatus === 'published' || 
    rawStatus === 'no ar' || 
    rawStatus === 'no_ar' || 
    p.published === true || 
    p.published === 'true'
  ) {
    p.status = 'published';
  } else if (rawStatus === 'scheduled') {
    p.status = 'scheduled';
  } else {
    p.status = 'draft';
  }

  // Normalize date using our strict priority-based validator
  p.date = getResolvedPostDate(p);

  // Normalize scheduling fields
  if (p.status === 'scheduled') {
    if (!p.publishAt) {
      p.publishAt = p.scheduledAt || p.publishAt;
    }
    // If the scheduled date has already passed, treat it as published!
    if (p.publishAt) {
      const parsedPublish = new Date(p.publishAt);
      if (!isNaN(parsedPublish.getTime()) && parsedPublish <= new Date()) {
        p.status = 'published';
        p.date = parsedPublish.toISOString(); // Set published date to match its scheduled publish time
      }
    }
  }

  // Ensure views is a number
  if (typeof p.views !== 'number') {
    p.views = Number(p.views) || 0;
  }

  // Ensure tags is an array
  if (!p.tags) {
    p.tags = [];
  } else if (typeof p.tags === 'string') {
    p.tags = (p.tags as string).split(',').map(t => t.trim()).filter(Boolean);
  }

  // Only explicit internal markers identify a test post. Editorial uses of the word
  // "teste" (for example, a vehicle review) are legitimate news headlines.
  const titleLower = String(p.title || '').trim().toLowerCase();
  const isTestByTitle =
    /^\[(?:teste|test)\](?:\s|$)/i.test(titleLower) ||
    /^(?:test post|test_post)(?:\s|:|-|$)/i.test(titleLower) ||
    /^teste\s+(?:interno|autom[aá]tico)(?:\s|:|-|$)/i.test(titleLower);
  
  if (p.isTestPost === 'true' || p.isTestPost === true || isTestByTitle) {
    p.isTestPost = true;
  } else {
    p.isTestPost = false;
  }

  return p as Post;
}
