export function getEditorialScore(post: Post): number {
  if (post.isTestPost) return 0;

  const baseViews = post.views || 0;
  let relevance = 0;

  const category = (post.category || '').toLowerCase();
  const title = (post.title || '').toLowerCase();
  const subtitle = (post.subtitle || '').toLowerCase();
  const content = (post.content || '').toLowerCase();
  const tags = (post.tags || []).map(t => t.toLowerCase());

  // Priority topics and matching rules
  const priorities = [
    { name: 'economia', points: 50 },
    { name: 'geopolítica', points: 50, terms: ['geopolítica', 'geopolitica', 'internacional', 'fronteira', 'guerra', 'acordo bilateral', 'tratado'] },
    { name: 'tecnologia', points: 50, terms: ['tecnologia', 'tech', 'inovação', 'digital'] },
    { name: 'inteligência artificial', points: 50, terms: ['inteligência artificial', 'inteligencia artificial', 'ia', 'gemini', 'gpt', 'ai', 'robótica', 'llm', 'machine learning'] },
    { name: 'energia', points: 50, terms: ['energia', 'petróleo', 'renovável', 'combustível', 'elétrica', 'solar', 'eólica', 'gas', 'gás'] },
    { name: 'política', points: 50, terms: ['política', 'politica', 'governo', 'senado', 'câmara', 'ministro', 'votação', 'eleição', 'eleições', 'lei', 'decreto'] }
  ];

  priorities.forEach(prio => {
    let matched = false;
    // Check main category
    if (category.includes(prio.name) || (prio.terms && prio.terms.some(t => category.includes(t)))) {
      matched = true;
    }
    // Check tags
    if (tags.some(tag => tag.includes(prio.name) || (prio.terms && prio.terms.some(t => tag.includes(t))))) {
      matched = true;
    }
    // Check title/subtitle/content keywords
    if (prio.terms && prio.terms.some(t => title.includes(t) || subtitle.includes(t))) {
      matched = true;
    }

    if (matched) {
      relevance += prio.points;
    }
  });

  return baseViews + relevance;
}

export function isPostUrgente(post: Post): boolean {
  if (post.isUrgente) return true;
  if (!post.date) return false;

  // Recency alone does not make a story urgent. It must carry an explicit
  // breaking-news signal and still be recent enough to justify the badge.
  const urgencyText = String((post.title || '') + ' ' + (post.tags || []).join(' ')).toLowerCase();
  const hasUrgencySignal = /\b(urgente|última hora|ultima hora|ao vivo|alerta)\b/.test(urgencyText);

  // Keep the explicit signal valid only while the story is still recent.
  const postTime = new Date(post.date).getTime();
  const now = new Date().getTime();
  const diffHours = (now - postTime) / (1000 * 60 * 60);

  return hasUrgencySignal && diffHours >= 0 && diffHours <= 12;
}

